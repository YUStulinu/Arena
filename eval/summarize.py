"""Collect the measured results into results/README.md: the network
evaluation (netem), bot strength, and the online ladder.

    python eval/summarize.py
"""

import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
ORDER = ["lan", "20ms", "50ms_1pct", "100ms_3pct", "150ms_5pct"]


def netem_section(out):
    files = {os.path.basename(f)[:-5]: json.load(open(f)) for f in glob.glob(os.path.join(R, "netem", "*.json"))}
    if not files:
        return
    out.append("## Network: latency, jitter and loss (netem)\n")
    out.append("The server and two native bot clients (chase against random) in three Linux network namespaces; netem on both ends of each "
               "client's link, so client-to-client latency is about twice the one-way delay. 60 frames per second, input delay 2 frames, "
               "rollback window 12 frames. Per scenario: every match; client values are averaged over both clients.\n")
    out.append("| scenario | matches | desyncs (checksums compared) | rollbacks / min | mean / max depth (frames) | mispredicted | "
               "mean / max error at a rollback (units) | stalls / min | upload / download (bytes/s) |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    for name in [n for n in ORDER if n in files] + [n for n in files if n not in ORDER]:
        ms = files[name]["matches"]
        cl = [c for m in ms for c in m["clients"] if "frames" in c]
        srv = [m["server"] for m in ms if m.get("server")]
        minutes = sum(c["seconds"] for c in cl) / 60
        rb = sum(c["rollbacks"] for c in cl)
        res = sum(c["resimulated"] for c in cl)
        mis = sum(c["mispredicted"] for c in cl)
        pred = sum(c["predicted"] for c in cl)
        err = sum(c["error_sum"] for c in cl)
        out.append(
            f"| {name} | {len(srv)} | {sum(s['desyncs'] for s in srv)} ({sum(s['checksums'] for s in srv)}) | "
            f"{rb / max(minutes, 1e-9):.0f} | {res / max(rb, 1):.1f} / {max(c['max_rollback'] for c in cl)} | "
            f"{mis / max(pred, 1):.0%} of {pred} predicted | {err / max(rb, 1):.3f} / {max(c['error_max'] for c in cl):.3f} | "
            f"{sum(c['stalls'] for c in cl) / max(minutes, 1e-9):.0f} | "
            f"{sum(c['bytes_out'] for c in cl) / sum(c['seconds'] for c in cl):.0f} / {sum(c['bytes_in'] for c in cl) / sum(c['seconds'] for c in cl):.0f} |"
        )
    out.append("")


def bots_section(out):
    p = os.path.join(R, "bots.json")
    if not os.path.exists(p):
        return
    b = json.load(open(p))
    out.append("## Bot strength\n")
    out.append(f"Round robin, {b['matches_per_pair']} matches per pair (half in each seat), {b['total_matches']} matches, {b['draws']} draws "
               "(no winner after 4 minutes). Elo by maximum likelihood (Bradley-Terry), random = 1000.\n")
    names = list(b["elo"])
    out.append("| bot | Elo | " + " | ".join(f"vs {n}" for n in names) + " |")
    out.append("|---" * (len(names) + 2) + "|")
    for n in sorted(names, key=lambda x: -b["elo"][x]):
        row = [f"{b['score_matrix'][n].get(m, ''):.2f}" if m != n else "—" for m in names]
        out.append(f"| {n} | {b['elo'][n]:.0f} | " + " | ".join(row) + " |")
    out.append("\nScores are points per match (win 1, draw 0.5) of the row against the column.\n")


def ladder_section(out):
    p = os.path.join(R, "ladder.json")
    if not os.path.exists(p):
        return
    s = json.load(open(p))["summary"]
    out.append("## Online ladder (matchmaker, Glicko-2)\n")
    out.append(f"{s['matches']} online matches in {s['minutes']} minutes between bots that keep joining the queue: {s['desyncs']} desyncs "
               f"in {s['checksums_compared']} compared checksums, {s['forfeits']} forfeits; a client sends {s['client_bytes_out_per_s']:.0f} "
               f"and receives {s['client_bytes_in_per_s']:.0f} bytes/s.\n")
    out.append("| player | rating | deviation | games | wins | draws |")
    out.append("|---|---|---|---|---|---|")
    for r in s["leaderboard"]:
        out.append(f"| {r['name']} | {r['rating']:.0f} | {r['rd']:.0f} | {r['games']} | {r['wins']} | {r['draws']} |")
    out.append("")


def main():
    out = ["# Arena: measured results\n", "Generated by `eval/summarize.py` from the JSON files here.\n"]
    netem_section(out)
    bots_section(out)
    ladder_section(out)
    open(os.path.join(R, "README.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
